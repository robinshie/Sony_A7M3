#!/usr/bin/env python3
"""Fit a compact sRGB effect to Sony's public ST/FL2 rendered examples.

This offline tool needs NumPy and Pillow. It does not read camera firmware.
"""
import argparse
from itertools import product
from pathlib import Path
import json

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
SCENES = {4: 'street', 5: 'river', 6: 'portrait'}
RGB_TO_YCC = np.array([[.2126, -.11457, .5], [.7152, -.38543, -.45415],
                       [.0722, .5, -.04585]])
YCC_TO_RGB = np.linalg.inv(RGB_TO_YCC)
SCALE = 1024


def load_pair(directory, scene):
    pair = []
    for look in (1, 4):
        with Image.open(directory / f'{scene}_{look}.jpg') as image:
            if image.size != (1500, 943) or image.mode != 'RGB':
                raise ValueError('Unexpected sample size or color mode')
            # The left panels contain ST and FL2; remove the white frame and labels.
            crop = image.crop((52, 278, 735, 732)).filter(ImageFilter.GaussianBlur(1.25))
            pair.append(np.asarray(crop, dtype=float)[::3, ::3].reshape(-1, 3) / 255)
    return pair


def features(a):
    y, cb, cr = a.T
    cb, cr = 2 * cb, 2 * cr
    weight = np.maximum(0, 1 - 8 * abs(y[:, None] - np.linspace(0, 1, 9)))
    return (weight[:, None, :] * np.stack([np.ones_like(y), cb, cr, cb**2, cr**2], axis=1)[..., None]).reshape(-1, 45)


def solve(pairs):
    a, b = [np.concatenate(part) @ RGB_TO_YCC for part in zip(*pairs)]
    v = features(a)
    diff = np.diff(np.eye(9), n=2, axis=0)
    smooth = np.kron(np.eye(5), diff.T @ diff)
    penalty = np.diag(np.repeat([.02, .08, .08, .30, .30], 9))
    # Stabilize colors absent from the three example scenes with a gentle prior.
    grid = np.array(list(product(np.linspace(0, 1, 7), repeat=3))) @ RGB_TO_YCC
    desired = grid.copy()
    desired[:, 0] = np.interp(grid[:, 0], [0, .25, .5, .75, 1], [.027, .285, .59, .815, .955])
    desired[:, 1:] *= .72
    q = features(grid)
    coefficients = np.linalg.solve(v.T @ v / len(a) + .003 * (smooth + penalty) + .006 * q.T @ q / len(q),
                                   v.T @ (b - a) / len(a) + .006 * q.T @ (desired - grid) / len(q))
    return np.rint(coefficients.reshape(5, 9, 3) * SCALE).astype(int)


def rgb_error(pair, coefficients=None):
    a, b = pair
    if coefficients is not None:
        ycc = a @ RGB_TO_YCC
        a = np.clip((ycc + features(ycc) @ coefficients.reshape(45, 3) / SCALE) @ YCC_TO_RGB, 0, 1)
    return round(float(np.abs(a - b).mean()) * 255, 2)


def c_header(coefficients):
    return ('/* Generated by research/fit_fl2_reference.py; Q10 deltas in Y, Cb, Cr order. */\n'
            'static const int16_t a7_fl2_coefficients[5][9][3]={\n' +
            ''.join('    {' + ','.join('{%d,%d,%d}' % tuple(row) for row in plane) + '},\n' for plane in coefficients) +
            '};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('samples', type=Path)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    pairs = {scene: load_pair(args.samples, scene) for scene in SCENES}
    coefficients = solve(pairs.values())
    diagonal = coefficients[0, :, 0] + np.arange(9) * (SCALE // 8)
    if np.any(np.diff(diagonal) < 0):
        raise ValueError('Fitted neutral luminance is not monotonic')
    scores = {SCENES[scene]: {
        'unmodified': rgb_error(pair),
        'fit': rgb_error(pair, coefficients),
        'held_out': rgb_error(pair, solve(p for i, p in pairs.items() if i != scene)),
    } for scene, pair in pairs.items()}
    original = json.loads((ROOT / 'recipes/fl-inspired-v0.json').read_text())
    recipe = dict(original, id='fl2-reference-srgb', name='FL2 Reference',
                  description='Approximate match to public Sony ST/FL2 render pairs. Input is display sRGB.',
                  linear_matrix=[[1, 0, 0], [0, 1, 0], [0, 0, 1]], hue_bands=[], saturation=1.0,
                  tone_curve=[[0, 0], [1, 1]], reference_ycc_q10=coefficients.tolist())
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'fl2-reference-srgb.json').write_text(json.dumps(recipe, indent=2) + '\n')
    (args.out / 'a7-fl-fl2-model.inc').write_text(c_header(coefficients))
    (args.out / 'fit.json').write_text(json.dumps(scores, indent=2) + '\n')
    print(json.dumps(scores))


if __name__ == '__main__':
    main()
