#!/usr/bin/env python3
"""Original, bold Leica Classic-inspired color design; not a vendor LUT.

The same Q10 coefficients drive the native Y/chroma grid and desktop previews.
Warm highlights, deep mid-shadows, a raised black floor, restrained blues/greens,
and relatively stronger reds. No grain, halation or spatial processing.
"""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
REFERENCE='https://leica-camera.com/en-US/photography/leica-looks'

def coefficients():
    result=[[[0,0,0] for _ in range(9)] for _ in range(5)]
    tone=[.030,.085,.195,.350,.540,.715,.845,.925,.965]
    cb=[.001,0,-.004,-.009,-.015,-.020,-.021,-.016,-.006]
    cr=[-.001,.002,.006,.011,.017,.021,.021,.016,.006]
    for k in range(9):
        result[0][k]=[round((tone[k]-k/8)*1024),round(cb[k]*1024),round(cr[k]*1024)]
        result[1][k]=[0,-164,25] # Cb attenuation; gentle channel cross-talk.
        result[2][k]=[0,-20,-41] # Red chroma remains relatively rich.
        result[3][k]=[0,-20,0]
    return result

def main():
    c=coefficients()
    header='/* Generated by research/leica_film_recipe.py; original Q10 design. */\n'
    header+='static const int16_t a7_leica_coefficients[5][9][3]={\n'
    header+=''.join('    {'+','.join('{%d,%d,%d}'%tuple(n) for n in p)+'},\n' for p in c)+'};\n'
    (ROOT/'payloads/a7-fl-leica-model.inc').write_text(header)
    recipe=json.loads((ROOT/'recipes/fl2-reference-srgb.json').read_text())
    recipe.update(id='leica-film-inspired',name='FL3 (Leica Film)',
        description='Original strong Classic-inspired warm film palette; not an official Leica LUT.',
        reference_ycc_q10=c,reference=REFERENCE)
    (ROOT/'recipes/leica-film-inspired.json').write_text(json.dumps(recipe,indent=2)+'\n')
    print('LEICA_FILM_MODEL_GENERATED')
if __name__=='__main__':main()
