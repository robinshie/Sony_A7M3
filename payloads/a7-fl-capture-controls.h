#ifndef A7_FL_CAPTURE_CONTROLS_H
#define A7_FL_CAPTURE_CONTROLS_H
#include "a7-fl-runtime.h"
#include "a7-fl-color.h"
/* Serialized by the caller. Never touches the 65-byte calibration tail.
 * Original CAP encodings differ: table 1 signed8, table 2 unsigned7. */
struct a7_capture_controls {
    struct a7_fl_api api;
    const uint8_t *stock[2],*legacy[2],*compress;
    const uint16_t *expand;
    uint8_t base[2][1280],current[2][1280];
#ifdef A7_FL_DUAL_LOOK
    uint8_t cinema[2][1280];
#ifdef A7_FL_LEICA_LOOK
    uint8_t leica[2][1280];
#endif
#endif
    int8_t low[2][1215],high[2][1215];
    unsigned prepared,initialized;
};
int a7_capture_prepare(struct a7_capture_controls *,const struct a7_fl_api *,
                       const uint8_t *const stock[2],const uint8_t *const legacy[2],
                       const uint16_t *,const uint8_t *);
int a7_capture_generate(const struct a7_capture_controls *,unsigned table,
                        const A7FLColorParams *,uint8_t out[1280]);
#ifdef A7_FL_FILM_CONTROLS
/* Generate the complete capture table in its native encoding, without I/O. */
int a7_capture_generate_curve(const struct a7_capture_controls *,unsigned table,int preset,
                               const A7FLColorParams *,const int curve[5],uint8_t out[1280]);
#endif
#ifdef A7_FL_DUAL_LOOK
int a7_capture_generate_preset(const struct a7_capture_controls *,unsigned table,int preset,
                               const A7FLColorParams *,uint8_t out[1280]);
#endif
/* Exact family recognition, including unsaved previews serialized by Sony. */
int a7_capture_recognize(const struct a7_capture_controls *,unsigned,const uint8_t [1280]);
/* Reads both properties; accepts only stock, legacy or exact generated bytes. */
int a7_capture_adopt(struct a7_capture_controls *,const A7FLColorParams *saved);
int a7_capture_verify(const struct a7_capture_controls *,int,const A7FLColorParams *);
/* Verify exact previous bytes, write/read both, rollback known touched bytes on
 * failure. A foreign table is never overwritten, even during rollback. */
int a7_capture_apply(struct a7_capture_controls *,int,const A7FLColorParams *);
#ifdef A7_FL_FILM_CONTROLS
/* FL3 only. New byte-exact recovery identity must be provided by the caller;
 * do not call this for camera I/O until the boot worklog is integrated. */
int a7_capture_apply_curve(struct a7_capture_controls *,int,const A7FLColorParams *,const int curve[5]);
#endif
#endif
